"""Turn the sliced sprites (sprites/*.png) into low-res, palette-reduced pixel art (pixel/*.png)
and pack them into sprites.js as base64 for the Phaser game."""
from PIL import Image
import os, base64, json

HERE = os.path.dirname(os.path.abspath(__file__))
SRC, OUT = os.path.join(HERE, "sprites"), os.path.join(HERE, "pixel")
os.makedirs(OUT, exist_ok=True)

# reference heights (px in the source) -> target pixel heights, applied per family so frames keep proportions
FAMILIES = {"mf_": (194, 44), "gm_": (295, 50), "kid_": (195, 30)}
SKIP = {"fart_cloud", "boost_cloud"}

def pixelate(im, scale, colors=18):
    w, h = im.size
    nw, nh = max(1, round(w * scale)), max(1, round(h * scale))
    small = im.convert("RGBA").resize((nw, nh), Image.LANCZOS)
    alpha = small.getchannel("A").point(lambda a: 255 if a >= 110 else 0)
    rgb = small.convert("RGB")
    q = rgb.quantize(colors=colors, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE).convert("RGB")
    q.putalpha(alpha)
    bbox = q.getbbox()
    return q.crop(bbox) if bbox else q

data = {}
for f in sorted(os.listdir(SRC)):
    name = f[:-4]
    if not f.endswith(".png") or name in SKIP or name.startswith("po_"):
        continue
    fam = next((k for k in FAMILIES if name.startswith(k)), None)
    if not fam:
        continue
    ref, target = FAMILIES[fam]
    im = Image.open(os.path.join(SRC, f))
    px = pixelate(im, target / ref)
    px.save(os.path.join(OUT, f))
    with open(os.path.join(OUT, f), "rb") as fh:
        data[name] = "data:image/png;base64," + base64.b64encode(fh.read()).decode()
    print(f"{name:18s} {px.size}")

with open(os.path.join(HERE, "sprites.js"), "w") as out:
    out.write("// Generated by tools_pixelate.py - do not edit by hand\nwindow.SPRITE_DATA = ")
    json.dump(data, out)
    out.write(";\n")
print(len(data), "sprites ->", os.path.getsize(os.path.join(HERE, "sprites.js")) // 1024, "KB")
